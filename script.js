let language = "en";
let selectedSide = null;
const result = document.getElementById("choiceResult");
const resultText = document.getElementById("resultText");
const header = document.querySelector(".site-header");
const menuToggle = document.getElementById("menuToggle");
const primaryNavigation = document.getElementById("primaryNavigation");
const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

function scrollOptions(block = "start") {
  return { behavior: prefersReducedMotion.matches ? "auto" : "smooth", block };
}

function setMenu(open) {
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", translations[language][open ? "menuClose" : "menuOpen"]);
  header.classList.toggle("menu-open", open);
  document.body.classList.toggle("menu-open", open);
}

function setLanguage(next) {
  language = next;
  document.documentElement.lang = next;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.innerHTML = translations[next][node.dataset.i18n];
  });
  document.querySelectorAll("[data-placeholder-i18n]").forEach((node) => {
    node.placeholder = translations[next][node.dataset.placeholderI18n];
  });
  document.getElementById("languageToggle").textContent = next === "en" ? "UZ" : "EN";
  menuToggle.setAttribute("aria-label", translations[next][menuToggle.getAttribute("aria-expanded") === "true" ? "menuClose" : "menuOpen"]);
  if (selectedSide) showChoice(selectedSide);
  if (!document.getElementById("applicationResult").hidden) buildApplication();
}

function showChoice(side) {
  selectedSide = side;
  document.querySelectorAll("[data-choice]").forEach((button) => {
    const selected = button.dataset.choice === side;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  result.hidden = false;
  resultText.textContent = translations[language][side === "classical" ? "classicalResult" : "progressiveResult"];
}

document.getElementById("languageToggle").addEventListener("click", () => setLanguage(language === "en" ? "uz" : "en"));
menuToggle.addEventListener("click", () => setMenu(menuToggle.getAttribute("aria-expanded") !== "true"));
primaryNavigation.addEventListener("click", (event) => {
  if (event.target.closest("a")) setMenu(false);
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});
window.addEventListener("resize", () => {
  if (window.innerWidth > 900) setMenu(false);
});

let scrollFrame = null;
window.addEventListener("scroll", () => {
  if (scrollFrame) return;
  scrollFrame = window.requestAnimationFrame(() => {
    header.classList.toggle("is-scrolled", window.scrollY > 24);
    scrollFrame = null;
  });
}, { passive: true });

if ("IntersectionObserver" in window) {
  const navigationLinks = [...primaryNavigation.querySelectorAll("a")];
  const sections = navigationLinks.map((link) => document.querySelector(link.hash)).filter(Boolean);
  const sectionObserver = new IntersectionObserver((entries) => {
    const visible = entries.filter((entry) => entry.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (!visible) return;
    navigationLinks.forEach((link) => {
      if (link.hash === `#${visible.target.id}`) link.setAttribute("aria-current", "true");
      else link.removeAttribute("aria-current");
    });
  }, { rootMargin: "-28% 0px -58%", threshold: [0, .25, .6] });
  sections.forEach((section) => sectionObserver.observe(section));
}

document.querySelectorAll("[data-choice]").forEach((button) => button.addEventListener("click", () => showChoice(button.dataset.choice)));
document.querySelectorAll("[data-side]").forEach((button) => button.addEventListener("click", () => {
  showChoice(button.dataset.side);
  document.getElementById("choose").scrollIntoView(scrollOptions());
}));

document.getElementById("shareButton").addEventListener("click", async () => {
  const sideName = selectedSide === "classical" ? translations[language].choiceClassical : translations[language].choiceProgressive;
  const shareText = language === "en"
    ? `I’m taking the ${sideName} side. Which side are you on? Join the debate: “Secondary schools should adopt a classical education model rather than a progressive one.”`
    : `Men ${sideName} ta’lim tomonidaman. Siz qaysi tomondasiz? Bahsga qo‘shiling: “O‘rta maktablar progressiv ta’lim o‘rniga klassik ta’lim modelini qabul qilishi kerak.”`;
  try {
    if (navigator.share) await navigator.share({ title: document.title, text: shareText, url: location.href });
    else {
      await navigator.clipboard.writeText(`${shareText} ${location.href}`);
      showToast(translations[language].copied);
    }
  } catch (error) {
    if (error.name !== "AbortError") showToast(translations[language].copied);
  }
});

function showToast(message) {
  const toast = document.getElementById("toast");
  toast.textContent = message;
  toast.classList.add("show");
  window.setTimeout(() => toast.classList.remove("show"), 2400);
}

const joinForm = document.getElementById("joinForm");
const applicationResult = document.getElementById("applicationResult");
const applicationText = document.getElementById("applicationText");
const telegramApplication = document.getElementById("telegramApplication");
const organiserTelegram = "Hsoxbdvu";

function selectedLabel(select) {
  return select.options[select.selectedIndex].text;
}

function buildApplication() {
  const values = {
    name: document.getElementById("fullName").value.trim(),
    school: document.getElementById("school").value.trim(),
    grade: document.getElementById("grade").value.trim(),
    side: selectedLabel(document.getElementById("preferredSide")),
    role: selectedLabel(document.getElementById("participantRole")),
    contact: document.getElementById("contact").value.trim()
  };
  const copy = translations[language];
  const message = `${copy.applicationHeading}\n\n${copy.applicationName}: ${values.name}\n${copy.applicationSchool}: ${values.school}, ${values.grade}\n${copy.applicationSide}: ${values.side}\n${copy.applicationRole}: ${values.role}\n${copy.applicationContact}: ${values.contact}`;
  applicationText.textContent = message;
  telegramApplication.href = `https://t.me/${organiserTelegram}?text=${encodeURIComponent(message)}`;
  return message;
}

joinForm.addEventListener("submit", (event) => {
  event.preventDefault();
  if (!joinForm.reportValidity()) return;
  buildApplication();
  applicationResult.hidden = false;
  applicationResult.scrollIntoView(scrollOptions("nearest"));
});

document.getElementById("copyApplication").addEventListener("click", async () => {
  await navigator.clipboard.writeText(buildApplication());
  showToast(translations[language].applicationCopied);
});
